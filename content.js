/*
  Информационная архитектура презентации «Idea to Decision».
  Заполняем только этот файл. Пустая строка = пункт ещё не заполнен (на слайде видна метка «заполнить»).

  Этап (stage) — один слайд, пункт в верхнем степпере
  ├─ title                             заголовок светлой панели
  ├─ insight {problem, value}         problem — «Было: …» выделенно в шапке слайда; value — вывод в шапке тёмной панели
  │    или {text}                     только вывод в шапке слайда (<b>…</b> — синее выделение)
  │    или {problem, then}            «Было: … → …» одной строкой-сдвигом в шапке слайда
  ├─ defaultRole                       id роли, открытой при входе на слайд (иначе первая)
  ├─ shared {people, process, tech}   таблица вкладки, общая для всех ролей этапа (вместо карточек)
  ├─ byRole {roleId: {process, tech}}  таблица вкладки для конкретной роли
  │    people [[было, стало]] · process [[процесс, было, стало, ценность]] · tech {was, added: текст | [[группа, текст]]}
  ├─ pairs                             true — если заполнена одна из карточек «Стало», таб показывает пару «Было → Стало»
  └─ roles[6]                          карточки-роли (сетка 3×2), клик открывает детализацию
     ├─ title, metric, caption, image  карточка
     ├─ effect, kpi {value, label}     эффект роли в шапке тёмной панели и мелкая цифра (withEffect)
     ├─ person                         кто принимает решение (метка 3-й карточки «Стало»)
     ├─ lenses {people, process, tech} табы тёмной панели: Люди / Процессы / Технологии
     └─ links [{title, items[[name, url, host]]}]  необязательно: вкладка «Артефакты» со ссылками
        ├─ lead                        вводный абзац
        ├─ before {title, text}        «Было»
        ├─ ai     {title, text}        «Стало» · С AI
        │    text может быть списком: 'пункт' или ['что', 'значение'] — строка-факт с крупной цифрой
        └─ human  {title, text}        «Стало» · <person>

  cycle: true — карточки 2×2 сверху по кругу со стрелками (порядок ролей = по часовой).
  rows: true вместе с matrix — сводка строками «шаг · процент · Было → Стало» вместо колонок.
  Этап со сводкой (matrix: 'заголовок') — карточки тоже шаги, а тёмная панель показывает таблицу «шаг | Было | Стало»
  по всем ролям сразу (Было — before, Стало — human или ai выбранного таба).

  Этап с таблицей (table) — вместо детализации по ролям тёмная панель показывает этап целиком,
  карточки ролей становятся шагами процесса (не кликаются), кликер идёт только по табам:
  table
  ├─ title                             заголовок панели
  └─ lenses {people, process, tech}
     ├─ before [title, text]           «Было»
     ├─ after  {title, items[], logos[]}  «Стало · что изменили»; logos — названия из LOGOS в app.js
     └─ numbers[3] {value, label, period, note, todo}   period — мелко под подписью   «В цифрах»; todo — цифру уточнить (пунктир)
*/

const lens = (lead = '', before = ['', ''], ai = ['', ''], human = ['', '']) => ({
  lead,
  before: { title: before[0], text: before[1] },
  ai: { title: ai[0], text: ai[1] },
  human: { title: human[0], text: human[1] },
});

const role = (id, title, metric, caption, image, person, lenses = {}) => ({
  id, title, metric, caption, image, person,
  lenses: { people: lens(), process: lens(), tech: lens(), ...lenses },
});

// Роль с эффектом в шапке тёмной панели: текст эффекта и мелкая цифра (kpi: {value, label} или null)
const withEffect = (effect, kpi, ...args) => ({ ...role(...args), effect, kpi });

const emptyRoles = () => [1, 2, 3, 4, 5, 6].map((n) => role(`r${n}`, '', '', '', '', ''));

